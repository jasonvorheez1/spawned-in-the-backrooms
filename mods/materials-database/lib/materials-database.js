/**
 * Get a single material by its ID (e.g. "iron", "oak", "diamond").
 * Returns the material object or null if not found.
 */
export function getMaterial(id) {
  return MATERIALS[id] || null;
}

/**
 * Get all materials in a category (e.g. "metals-ferrous", "liquids").
 * Returns an array of { id, ...materialProps }.
 */
export function getMaterialsByCategory(category) {
  const results = [];
  for (const id in MATERIALS) {
    if (MATERIALS[id].category === category) {
      results.push({ id, ...MATERIALS[id] });
    }
  }
  return results;
}

/**
 * Get all category IDs with their display names and icons.
 * Returns an array of { id, name, icon }.
 */
export function getCategories() {
  const results = [];
  for (const id in CATEGORIES) {
    results.push({ id, name: CATEGORIES[id].name, icon: CATEGORIES[id].icon });
  }
  return results;
}

